/**
 * Saca el esquema real de la base a un fichero SQL.
 *
 * El esquema de esta base **no estaba escrito en ninguna parte**: lo creaban 36
 * ficheros al vuelo, con `CREATE TABLE IF NOT EXISTS` y `ALTER TABLE … IF NOT
 * EXISTS`, la primera vez que alguien entraba en la pantalla que los ejecuta.
 * Eso quiere decir que nadie podía decir qué tablas hay sin arrancar la
 * aplicación y pasar por todas las pantallas, que no se podía levantar una base
 * de pruebas igual a la de verdad, y que un cambio no tenía marcha atrás porque
 * no había «atrás».
 *
 * Esto lee el catálogo de Postgres y escribe lo que hay. El resultado es la
 * migración 0001: el punto de partida. A partir de ahí cada cambio es un
 * fichero numerado que se revisa y se aplica con `npm run migra`.
 *
 * Se puede volver a ejecutar cuando se quiera para comparar lo escrito con lo
 * que hay de verdad:
 *
 *   node scripts/saca-el-esquema.mjs                 → migrations/0001-lo-que-hay-hoy.sql
 *   node scripts/saca-el-esquema.mjs --a otro.sql    → a donde se diga
 *
 * No lleva datos, solo la forma. Y no borra nada: escribe un fichero.
 */
import fs from "node:fs";
import path from "node:path";
import pg from "pg";

const RAIZ = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");

function delEntorno(nombre) {
  if (process.env[nombre]) return process.env[nombre];
  const fichero = path.join(RAIZ, ".env.local");
  if (!fs.existsSync(fichero)) return "";
  const l = fs.readFileSync(fichero, "utf8").split(/\r?\n/).filter((x) => x.startsWith(nombre + "="));
  return l.length ? l[l.length - 1].slice(nombre.length + 1).trim().replace(/^["']|["']$/g, "") : "";
}

const donde = (() => {
  const i = process.argv.indexOf("--a");
  return i > 0 && process.argv[i + 1]
    ? path.resolve(process.argv[i + 1])
    : path.join(RAIZ, "migrations", "0001-lo-que-hay-hoy.sql");
})();

const cadena = delEntorno("DATABASE_URL") || delEntorno("POSTGRES_URL");
if (!cadena) {
  console.error("Sin DATABASE_URL no hay de dónde sacarlo.");
  process.exit(1);
}
const pool = new pg.Pool({ connectionString: cadena });

/** Un nombre entre comillas solo si lo necesita. */
const nom = (s) => (/^[a-z_][a-z0-9_]*$/.test(s) ? s : `"${s}"`);

async function main() {
  const { rows: tablas } = await pool.query(`
    SELECT c.oid, c.relname AS tabla
      FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'public' AND c.relkind = 'r'
     ORDER BY c.relname`);

  const partes = [];
  partes.push(`-- ${"-".repeat(74)}`);
  partes.push("-- 0001 · Lo que ya había");
  partes.push("--");
  partes.push("-- Generado por scripts/saca-el-esquema.mjs leyendo la base de verdad.");
  partes.push("-- No se escribe a mano: si hay que cambiar algo, se hace en una migración");
  partes.push("-- nueva, no aquí. Este fichero es la foto del día en que se empezó a llevar");
  partes.push("-- la cuenta.");
  partes.push("--");
  partes.push(`-- ${tablas.length} tablas.`);
  partes.push(`-- ${"-".repeat(74)}`);
  partes.push("");

  // ── Las tablas y sus columnas ───────────────────────────────────────────
  for (const t of tablas) {
    const { rows: cols } = await pool.query(
      `SELECT a.attname AS nombre,
              format_type(a.atttypid, a.atttypmod) AS tipo,
              a.attnotnull AS obligatoria,
              a.attidentity AS identidad,
              pg_get_expr(d.adbin, d.adrelid) AS porDefecto
         FROM pg_attribute a
         LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped
        ORDER BY a.attnum`,
      [t.oid]
    );

    const lineas = cols.map((c) => {
      let l = `  ${nom(c.nombre)} ${c.tipo}`;
      if (c.identidad === "a") l += " GENERATED ALWAYS AS IDENTITY";
      else if (c.identidad === "d") l += " GENERATED BY DEFAULT AS IDENTITY";
      else if (c.pordefecto) l += ` DEFAULT ${c.pordefecto}`;
      if (c.obligatoria) l += " NOT NULL";
      return l;
    });

    partes.push(`CREATE TABLE IF NOT EXISTS ${nom(t.tabla)} (`);
    partes.push(lineas.join(",\n"));
    partes.push(");");
    partes.push("");
  }

  // ── Las reglas: clave primaria, únicos, comprobaciones y relaciones ──────
  //
  // Van después de todas las tablas porque una relación necesita que la otra
  // exista, y así el fichero se aplica de un tirón sobre una base vacía.
  const { rows: reglas } = await pool.query(`
    SELECT c.relname AS tabla, con.conname AS nombre, con.contype AS tipo,
           pg_get_constraintdef(con.oid) AS definicion
      FROM pg_constraint con
      JOIN pg_class c ON c.oid = con.conrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
     WHERE con.contype IN ('p', 'u', 'c', 'f')
     ORDER BY CASE con.contype WHEN 'p' THEN 1 WHEN 'u' THEN 2 WHEN 'c' THEN 3 ELSE 4 END,
              c.relname, con.conname`);

  if (reglas.length) {
    partes.push(`-- ${"-".repeat(74)}`);
    partes.push("-- Claves, únicos, comprobaciones y relaciones");
    partes.push("--");
    partes.push("-- `ADD CONSTRAINT` no entiende de IF NOT EXISTS, así que cada una se");
    partes.push("-- pregunta antes si ya está. Así el fichero se puede aplicar sobre la base");
    partes.push("-- que ya existe sin que pase nada.");
    partes.push(`-- ${"-".repeat(74)}`);
    partes.push("");
    for (const r of reglas) {
      partes.push(`DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '${r.nombre}') THEN
    ALTER TABLE ${nom(r.tabla)} ADD CONSTRAINT ${nom(r.nombre)} ${r.definicion};
  END IF;
END $$;`);
    }
    partes.push("");
  }

  // ── Los índices que no vienen de una regla ───────────────────────────────
  const { rows: indices } = await pool.query(`
    SELECT i.indexdef AS definicion
      FROM pg_indexes i
      LEFT JOIN pg_constraint con ON con.conname = i.indexname
     WHERE i.schemaname = 'public' AND con.oid IS NULL
     ORDER BY i.tablename, i.indexname`);

  if (indices.length) {
    partes.push(`-- ${"-".repeat(74)}`);
    partes.push("-- Índices");
    partes.push(`-- ${"-".repeat(74)}`);
    partes.push("");
    for (const i of indices) {
      partes.push(i.definicion.replace(/^CREATE INDEX /, "CREATE INDEX IF NOT EXISTS ")
                              .replace(/^CREATE UNIQUE INDEX /, "CREATE UNIQUE INDEX IF NOT EXISTS ") + ";");
    }
    partes.push("");
  }

  fs.mkdirSync(path.dirname(donde), { recursive: true });
  fs.writeFileSync(donde, partes.join("\n"), "utf8");
  console.log(`${tablas.length} tablas, ${reglas.length} reglas y ${indices.length} índices escritos en`);
  console.log(`  ${donde}`);
  await pool.end();
}

main().catch((e) => { console.error(e); process.exit(1); });
